# Builds firmware/src/th_strings.h: the English -> Thai table the Thai firmware looks up at draw time.
# Sources, later ones win:  l10n/th/strings.tsv, l10n/th/strings-titles.tsv, l10n/th/community/thai_ui_strings.json
# In the Thai text a | (or a zero width space) marks where a line may break between words.
# Run:  powershell -File scripts/thai/build-thai-strings.ps1
Add-Type -AssemblyName System.Web.Extensions
$root = Split-Path (Split-Path $PSScriptRoot)
$map = New-Object 'System.Collections.Generic.Dictionary[string,string]' ([StringComparer]::Ordinal)
$zw = [string][char]0x200B
foreach ($f in 'strings.tsv', 'strings-titles.tsv') {
  foreach ($line in [IO.File]::ReadAllLines("$root\l10n\th\$f", [Text.Encoding]::UTF8)) {
    if ($line.StartsWith('#') -or $line.Trim() -eq '') { continue }
    $i = $line.IndexOf("`t")
    if ($i -lt 1) { continue }
    $map[$line.Substring(0, $i)] = $line.Substring($i + 1).Replace('|', $zw)
  }
}
$js = New-Object System.Web.Script.Serialization.JavaScriptSerializer
$com = $js.DeserializeObject([IO.File]::ReadAllText("$root\l10n\th\community\thai_ui_strings.json", [Text.Encoding]::UTF8))
foreach ($k in $com.Keys) { $map[$k] = ([string]$com[$k]).Replace('|', $zw) }

function CStr([string]$s) {
  $sb = New-Object Text.StringBuilder
  [void]$sb.Append('"')
  foreach ($b in [Text.Encoding]::UTF8.GetBytes($s)) {
    if ($b -eq 34) { [void]$sb.Append('\"') }
    elseif ($b -eq 92) { [void]$sb.Append('\\') }
    elseif ($b -ge 32 -and $b -lt 127 -and $b -ne 63) { [void]$sb.Append([char]$b) }
    else { [void]$sb.Append('\' + [Convert]::ToString($b, 8).PadLeft(3, '0')) }
  }
  [void]$sb.Append('"')
  $sb.ToString()
}
$keys = New-Object 'System.Collections.Generic.List[string]'
$keys.AddRange($map.Keys)
$keys.Sort([StringComparer]::Ordinal)
$o = New-Object Text.StringBuilder
[void]$o.Append("// Generated by scripts/thai/build-thai-strings.ps1 - do not edit.`n// English text as the firmware draws it -> Thai. Sorted bytewise for binary search.`n#pragma once`nstruct ThStr { const char *en; const char *th; };`nstatic const ThStr TH_STR[] = {`n")
foreach ($k in $keys) { [void]$o.Append('  {' + (CStr $k) + ', ' + (CStr $map[$k]) + "},`n") }
[void]$o.Append("};`nstatic const int TH_STR_N = $($keys.Count);`n")
[IO.File]::WriteAllText("$root\firmware\src\th_strings.h", $o.ToString(), (New-Object Text.UTF8Encoding $false))
"$($keys.Count) strings"